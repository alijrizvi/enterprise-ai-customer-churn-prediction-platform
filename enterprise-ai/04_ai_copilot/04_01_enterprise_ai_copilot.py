# =========================================================
# 8. ENTERPRISE PROMPT PIPELINE
# =========================================================#
# Purpose:
#
# Assemble conversation history and communicate with
# the Enterprise AI Copilot.
#
# Separating prompt construction from business logic
# makes the application easier to maintain and reuse.
# =========================================================


def executive_copilot(

    messages,

    model="gpt-4.1-mini",

    temperature=0.2

):

    response = client.chat.completions.create(

        model=model,

        messages=messages,

        temperature=temperature

    )

    return response.choices[0].message.content

# =========================================================
# 9. GENERATE INITIAL EXECUTIVE REPORT
